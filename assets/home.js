  let shown = [], active = -1;

  function score(t, words) {
    let s = 0;
    for (const w of words) {
      if (!t.hay.includes(w)) return -1;
      if (t.name_l.startsWith(w)) s += 6;
      else if (new RegExp("\\b" + w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).test(t.name_l)) s += 4;
      else if (new RegExp("\\b" + w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).test(t.hay)) s += 2;
      else s += 1;
    }
    return s;
  }

